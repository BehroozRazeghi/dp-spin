def _count_selected(plan_path: Path) -> int | None:
    """Count admitted atoms or retained clusters in a saved JSON release object."""
    if not plan_path.exists():
        return None
    try:
        plan = read_json(plan_path)
    except Exception:
        return None
    if isinstance(plan.get("clusters"), list):
        return len(plan["clusters"])
    if isinstance(plan.get("selected_atoms"), list):
        return len(plan["selected_atoms"])
    return None


def _read_urania_metrics(path: Path) -> dict[str, Any]:
    """Read URANIA-style baseline metrics when the metrics file is present."""
    metrics_path = path / "urania_cluster_public_keyword_metrics.json"
    if not metrics_path.exists():
        return {}
    try:
        return read_json(metrics_path)
    except Exception:
        return {}


def collect_baseline_rows(baseline_dir: Path) -> list[dict[str, Any]]:
    """Collect method metadata for baseline artifacts present in one output directory."""
    rows: list[dict[str, Any]] = []
    urania_metrics = _read_urania_metrics(baseline_dir)
    for spec in BASELINE_DESCRIPTIONS:
        source = baseline_dir / spec["file"]
        row = dict(spec)
        row["available"] = bool(source.exists())
        row["source_file"] = str(source)
        row["num_released_items"] = _count_selected(source) if source.suffix == ".json" else None
        if spec["method"].startswith("URANIA") and urania_metrics:
            row["epsilon_total"] = urania_metrics.get("epsilon_total")
            row["delta_total"] = urania_metrics.get("delta_total")
            row["num_released_items"] = urania_metrics.get("num_clusters_released")
        rows.append(row)
    return rows


def _latex_escape(s: Any) -> str:
    s = "" if s is None else str(s)
    for a, b in {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }.items():
        s = s.replace(a, b)
    return s


def write_baseline_latex(df: pd.DataFrame, path: Path) -> None:
    """Write a LaTeX table describing the available baselines and their privacy boundaries."""
    rows = []
    cols = ["method", "class", "decoder_input", "dp", "released_object"]
    lines = [
        "% Auto-generated by src.baseline_report. Requires booktabs.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Baseline methods and privacy boundaries. Non-private baselines are utility references only. DP baselines release only noisy statistics over fixed public vocabularies or public categories.}",
        r"\label{tab:baseline-privacy-boundary}",
        r"\scriptsize",
        r"\begin{tabular}{p{0.17\linewidth} p{0.18\linewidth} p{0.25\linewidth} p{0.14\linewidth} p{0.18\linewidth}}",
        r"\toprule",
        r"Method & Role & Decoder input & DP? & Released object \\",
        r"\midrule",
    ]
    for _, r in df.iterrows():
        vals = [_latex_escape(r[c]) for c in cols]
        lines.append(" & ".join(vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    """Generate baseline metadata reports from the command line."""
    p = argparse.ArgumentParser(description="Create a table describing baseline privacy boundaries.")
    p.add_argument("--baseline-dir", required=True)
    p.add_argument("--output-dir", required=True)
    args = p.parse_args()
    base = Path(args.baseline_dir)
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    rows = collect_baseline_rows(base)
    df = pd.DataFrame(rows)
    df.to_csv(out / "baseline_methods.csv", index=False)
    write_json(rows, out / "baseline_methods.json")
    write_baseline_latex(df, out / "baseline_methods_table.tex")
    print(f"Wrote baseline report to {out}")


if __name__ == "__main__":
    main()
