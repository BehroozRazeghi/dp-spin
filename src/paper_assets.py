def collect_assets(out: str = "outputs/cfpb") -> None:
    """Create the canonical ``paper_assets`` folder for one completed run."""
    out_path = Path(out)
    assets = out_path / "paper_assets"
    figures = assets / "figures"
    tables = assets / "tables"
    raw_tables = assets / "raw_tables"
    diagnostics = assets / "diagnostics"
    text = assets / "text"

    # These folders are generated artifacts.  Clean them before recollecting
    # assets so old file names, especially legacy probe/probe aliases, do not
    # remain after the reporting code changes.
    for directory in [figures, tables, raw_tables, diagnostics, text]:
        clean_generated_directory(directory)
    remove_legacy_probe_assets(out_path / "paper_figures", figures)

    manifest_lines = [
        "# DP-SPIN paper assets manifest",
        "",
        f"Canonical paper assets generated from `{out_path}`.",
        "",
        "Use `paper_assets/figures` and `paper_assets/tables` when writing the paper.",
        "Treat `paper_figures` and `paper_tables` as intermediate folders.",
        "",
        "## LaTeX tables",
    ]

    for spec in latex_table_specs(out_path):
        ok, msg = copy_latex_table(spec, tables)
        manifest_lines.append(("- " if ok else "- MISSING: ") + msg)

    manifest_lines.append("\n## Figures")
    for spec in figure_specs(out_path):
        ok, msg = copy_file(spec, figures)
        manifest_lines.append(("- " if ok else "- MISSING: ") + msg)

    manifest_lines.append("\n## Raw tables")
    for spec in raw_table_specs(out_path):
        ok, msg = copy_file(spec, raw_tables)
        manifest_lines.append(("- " if ok else "- MISSING: ") + msg)

    manifest_lines.append("\n## Diagnostics")
    for spec in diagnostic_specs(out_path):
        ok, msg = copy_file(spec, diagnostics)
        manifest_lines.append(("- " if ok else "- MISSING: ") + msg)

    # Optional OpenAI-generated material.  The names below cover the current and
    # older output conventions; missing files are simply recorded in the manifest.
    manifest_lines.append("\n## Optional OpenAI text/tables")
    optional_openai = [
        FileCopySpec(out_path / "baselines" / "cfpb_template" / "urania_cluster_public_keyword_summary.txt", "urania_cluster_public_keyword_summary.txt", "template URANIA-style baseline summary"),
        FileCopySpec(out_path / "openai_all" / "latex" / "openai_results_text.tex", "openai_results_text.tex", "OpenAI results prose"),
        FileCopySpec(out_path / "openai_all" / "latex" / "openai_qualitative_examples.md", "openai_qualitative_examples.md", "OpenAI qualitative examples"),
        FileCopySpec(out_path / "openai" / "baselines" / "cfpb_openai" / "urania_cluster_public_keyword_summary.txt", "openai_urania_cluster_public_keyword_summary.txt", "OpenAI URANIA-style baseline summary"),
        FileCopySpec(out_path / "openai" / "judgments" / "judgments.json", "openai_judgments.json", "OpenAI rubric judgments"),
    ]
    for spec in optional_openai:
        destination = text if spec.destination_name.endswith((".tex", ".md")) else raw_tables
        ok, msg = copy_file(spec, destination)
        manifest_lines.append(("- " if ok else "- MISSING: ") + msg)

    (assets / "MANIFEST.md").write_text("\n".join(manifest_lines) + "\n", encoding="utf-8")
    print(f"Paper assets written to {assets}")
    print(f"Manifest: {assets / 'MANIFEST.md'}")


def main() -> None:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description="Collect final paper-facing DP-SPIN assets.")
    parser.add_argument("--out", default="outputs/cfpb", help="Root output directory for the experiment family.")
    args = parser.parse_args()
    collect_assets(args.out)


if __name__ == "__main__":
    main()
