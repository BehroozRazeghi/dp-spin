"""Collect publication figures, tables, diagnostics, and text artifacts.

The collector copies selected outputs from completed experiment and report directories into a stable ``paper_assets`` hierarchy. 
It does not recompute metrics or privacy mechanisms. 
Missing optional sources are recorded in the manifest rather than synthesized.
"""
from __future__ import annotations

import argparse
import re
import shutil
from dataclasses import dataclass
from pathlib import Path


LEGACY_PROBE_ASSET_NAMES = {
    # Older controlled-probe figures used the term ``probe`` in file names.
    # Current assets use ``probe``. These legacy names are removed on
    # collection so stale files cannot remain beside the regenerated assets.
    "fig6_probe_admission_vs_support.png",
    "fig7_probe_non_private_rank_vs_support.png",
    "fig6_cfpb_probe_admission_vs_support.png",
    "fig7_cfpb_probe_non_private_rank_vs_support.png",
    "probe_admission.png",
    "probe_admission_unused.png",
}


def clean_generated_directory(path: Path) -> None:
    """Remove files from a generated asset directory before recollecting assets."""
    path.mkdir(parents=True, exist_ok=True)
    for item in path.iterdir():
        if item.is_file() or item.is_symlink():
            item.unlink()
        elif item.is_dir():
            shutil.rmtree(item)


def remove_legacy_probe_assets(*directories: Path) -> None:
    """Delete superseded files that use the earlier controlled-probe naming."""
    for directory in directories:
        for name in LEGACY_PROBE_ASSET_NAMES:
            path = directory / name
            if path.exists():
                path.unlink()


@dataclass(frozen=True)
class LatexTableSpec:
    """Describe one LaTeX table copied into the publication-asset directory."""

    source: Path
    destination_name: str
    caption: str
    label: str
    compact: bool = True


@dataclass(frozen=True)
class FileCopySpec:
    """Describe one source file and its destination in the asset directory."""

    source: Path
    destination_name: str
    description: str


def sanitize_label(label: str) -> str:
    """Convert a label to the restricted character set used for LaTeX references."""
    label = label.replace("_", "-").lower()
    label = re.sub(r"[^a-z0-9:.-]+", "-", label)
    label = re.sub(r"-+", "-", label).strip("-")
    return label or "tab:dpspin"


def has_table_environment(text: str) -> bool:
    """Check whether a LaTeX file already contains a table environment."""
    return "\\begin{table" in text and "\\end{table" in text


def wrap_latex_fragment(fragment: str, caption: str, label: str, *, compact: bool) -> str:
    """Wrap a legacy ``tabular`` fragment in a complete LaTeX table environment.
    
    Current report generators already emit complete table environments. This path is
    kept only for previously generated fragments.
    """
    env = "table" if compact else "table*"
    size = r"\small" if compact else r"\scriptsize"
    label = sanitize_label(label)
    return "\n".join(
        [
            "% Auto-generated by src.paper_assets from a LaTeX fragment.",
            "% Requires: \\usepackage{booktabs}",
            rf"\begin{{{env}}}[t]",
            r"\centering",
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
            size,
            fragment.strip(),
            rf"\end{{{env}}}",
            "",
        ]
    )


def copy_latex_table(spec: LatexTableSpec, destination_dir: Path) -> tuple[bool, str]:
    """Copy or wrap one LaTeX table into the canonical table asset folder."""
    if not spec.source.exists():
        return False, f"missing table source `{spec.source}`"

    text = spec.source.read_text(encoding="utf-8")
    if not has_table_environment(text):
        text = wrap_latex_fragment(text, spec.caption, spec.label, compact=spec.compact)

    destination = destination_dir / spec.destination_name
    destination.write_text(text, encoding="utf-8")
    return True, f"`tables/{spec.destination_name}`: {spec.caption}"


def copy_file(spec: FileCopySpec, destination_dir: Path) -> tuple[bool, str]:
    """Copy one non-LaTeX file into a canonical asset subfolder."""
    if not spec.source.exists():
        return False, f"missing file source `{spec.source}`"
    destination = destination_dir / spec.destination_name
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(spec.source, destination)
    return True, f"`{destination_dir.name}/{spec.destination_name}`: {spec.description}"


